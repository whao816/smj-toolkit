def test_frontier_weights_unlabelled_when_control_missing(workdir):
    stage = workdir / "opt"
    stage.mkdir()
    write_cube(stage / "cube_001_eigenstate_00010_spin_1.cube",
               [(16, 0.0, 0.0, 0.0)], counts=(4, 4, 4), step_au=0.5,
               density=lambda i, j, k: 0.0)
    report = frontier_weights(stage)
    assert report[0]["orbit"] is None
    assert report[0]["anchor_fraction"] is None  # 全箱密度为 0：报告 None，不除零


def test_read_cube_rejects_nonorthogonal_grid(workdir):
    path = workdir / "bad.cube"
    path.write_text(
        "a\nb\n1 0 0 0\n2 0.1 0.0 0.0\n2 0.05 0.1 0.0\n2 0.0 0.0 0.1\n"
        "16 0.0 0 0 0\n" + " ".join(["0.0"] * 8) + "\n", encoding="utf-8")
    with pytest.raises(ValueError, match="轴对齐"):
        read_cube(path)


def test_read_cube_rejects_voxel_count_mismatch(workdir):
    path = workdir / "short.cube"
    path.write_text(
        "a\nb\n1 0 0 0\n2 0.1 0 0\n2 0 0.1 0\n2 0 0 0.1\n"
        "16 0.0 0 0 0\n0.0 0.0\n", encoding="utf-8")
    with pytest.raises(ValueError, match="体素数不符"):
        read_cube(path)
