"""`smj.cube` 的解析与锚定轨道权重。"""

from __future__ import annotations

import math

import pytest

from smj.cube import BOHR, anchor_weight, frontier_weights, read_cube


def write_cube(path, atoms, *, origin=(0.0, 0.0, 0.0), counts=(8, 8, 8),
               step_au=0.2, density=None, signed=None):
    """写一个最小 cube：坐标与步长按 bohr，体素按 x 变化最快的顺序输出。

    ``atoms`` 为 ``[(Z, x_A, y_A, z_A)]``；``density``/``signed`` 是
    ``(i, j, k) -> 值`` 的可调用对象（二选一）。
    """
    nx, ny, nz = counts
    lines = ["cube test", "generated by tests"]
    lines.append("%d %.6f %.6f %.6f" % (len(atoms), *(c / BOHR for c in origin)))
    for axis, n in enumerate((nx, ny, nz)):
        vector = [0.0, 0.0, 0.0]
        vector[axis] = step_au
        lines.append("%d %.6f %.6f %.6f" % (n, *vector))
    for z, x, y, zc in atoms:
        lines.append("%d 0.000000 %10.6f %10.6f %10.6f" % (z, x / BOHR, y / BOHR, zc / BOHR))
    chunk = []
    for k in range(nz):
        for j in range(ny):
            for i in range(nx):
                value = signed(i, j, k) if signed is not None else density(i, j, k)
                chunk.append("%14.8E" % value)
                if len(chunk) == 6:
                    lines.append(" ".join(chunk))
                    chunk = []
    if chunk:
        lines.append(" ".join(chunk))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _coords(i, j, k, *, step_a=0.2, origin=(0.0, 0.0, 0.0)):
    return (origin[0] + i * step_a, origin[1] + j * step_a, origin[2] + k * step_a)


def _gaussian(kind, center, *, sigma=0.45, origin=(0.0, 0.0, 0.0)):
    def value(i, j, k):
        x, y, z = _coords(i, j, k, origin=origin)
        r2 = (x - center[0]) ** 2 + (y - center[1]) ** 2 + (z - center[2]) ** 2
        rho = math.exp(-r2 / (2.0 * sigma ** 2))
        return math.copysign(math.sqrt(rho), x - center[0]) if kind == "psi" else rho
    return value


def test_read_cube_units_and_fastest_axis(workdir):
    """步长按 bohr 写、坐标换算成 Å；values[i, j, k] 的下标 i 就是 x 轴。"""
    values = {}

    def spike(i, j, k):
        return 1.0 if (i, j, k) == (1, 2, 3) else 0.0

    path = workdir / "spike.cube"
    write_cube(path, [(16, 0.0, 0.0, 0.0)], step_au=0.2 / BOHR, density=spike)
    cube = read_cube(path)
    assert cube.shape == (8, 8, 8)
    assert cube.steps == pytest.approx((0.2, 0.2, 0.2))
    assert cube.values[1, 2, 3] == pytest.approx(1.0)
    assert cube.values.sum() == pytest.approx(1.0)


def test_anchor_weight_localized_orbital(workdir):
    """轨道全落在第一个 S 的球内 → 该锚 100%，远处另一个 S 0%。"""
    path = workdir / "local.cube"
    write_cube(path, [(16, 0.0, 0.0, 0.0), (16, 12.0, 0.0, 0.0)],
               origin=(-2.0, -2.0, -2.0), counts=(21, 21, 21), step_au=0.2 / BOHR,
               density=_gaussian("rho", (0.0, 0.0, 0.0), origin=(-2.0, -2.0, -2.0)))
    weights = anchor_weight(read_cube(path), radius=1.6)
    first, second = weights["anchors"]
    assert first["element"] == "S" and first["index"] == 1
    assert first["fraction"] == pytest.approx(1.0, abs=0.02)
    assert second["fraction"] == 0.0
    assert weights["fraction"] == pytest.approx(1.0, abs=0.02)
    assert weights["signed_cube"] is False


def test_signed_cube_is_squared(workdir):
    """带符号的 ψ（有负值）要先平方再积分，占比不变。"""
    path = workdir / "psi.cube"
    write_cube(path, [(16, 0.0, 0.0, 0.0)],
               origin=(-2.0, -2.0, -2.0), counts=(21, 21, 21), step_au=0.2 / BOHR,
               signed=_gaussian("psi", (0.0, 0.0, 0.0), origin=(-2.0, -2.0, -2.0)))
    cube = read_cube(path)
    assert cube.signed is True
    weights = anchor_weight(cube, radius=1.6)
    assert weights["fraction"] == pytest.approx(1.0, abs=0.02)


def test_frontier_weights_maps_requests_to_files(workdir):
    """cube 序号与 control.in 的请求顺序一一对应（HOMO-1/HOMO/LUMO/LUMO+1）。"""
    stage = workdir / "opt"
    stage.mkdir()
    (stage / "control.in").write_text(
        "xc pbe\n"
        "output cube eigenstate HOMO-1\n"
        "output cube eigenstate HOMO\n"
        "output cube eigenstate LUMO\n"
        "output cube eigenstate LUMO+1\n"
        "relax_geometry bfgs 1.e-2\n",
        encoding="utf-8")
    for order, eigen in enumerate((122, 123, 124, 125), start=1):
        write_cube(stage / ("cube_%03d_eigenstate_%05d_spin_1.cube" % (order, eigen)),
                   [(16, 0.0, 0.0, 0.0)],
                   origin=(-2.0, -2.0, -2.0), counts=(21, 21, 21),
                   step_au=0.2 / BOHR, density=_gaussian("rho", (0.0, 0.0, 0.0), origin=(-2.0, -2.0, -2.0)))
    report = frontier_weights(stage)
    assert [item["orbit"] for item in report] == ["HOMO-1", "HOMO", "LUMO", "LUMO+1"]
    assert [item["eigenstate"] for item in report] == [122, 123, 124, 125]
    assert all(item["anchor_fraction"] == pytest.approx(1.0, abs=0.02) for item in report)
    assert report[0]["file"] == "cube_001_eigenstate_00122_spin_1.cube"


